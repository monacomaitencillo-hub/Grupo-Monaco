// ── Import to Firestore ───────────────────────────────────────────────────
async function importEmployees() {
  const col = db.collection('rrhh_employees');
  let imported = 0;
  let errors   = 0;

  for (const emp of employees) {
    try {
      // Add server timestamp
      const doc = {
        ...emp,
        createdAt: admin.firestore.FieldValue.serverTimestamp(),
        updatedAt: admin.firestore.FieldValue.serverTimestamp(),
      };
      const ref = await col.add(doc);
      console.log(`✅ [${emp.restaurantId}] ${emp.nombre} → ${ref.id}`);
      imported++;
    } catch (err) {
      console.error(`❌ Error importing ${emp.nombre}:`, err.message);
      errors++;
    }
  }

  console.log(`\n──────────────────────────────────────`);
  console.log(`Importados: ${imported} empleados`);
  if (errors > 0) console.log(`Errores:    ${errors}`);
  console.log(`Colección: rrhh_employees`);

  process.exit(0);
}

importEmployees().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
